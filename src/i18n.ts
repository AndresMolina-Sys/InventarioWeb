export type TranslationParameters = Readonly<Record<string, string | number>>;

export const translations: Readonly<Record<AppLanguage, Readonly<Record<TranslationKey, string>>>> = {
  es: spanish,
  en: english,
};

export const LOCALE_BY_LANGUAGE: Readonly<Record<AppLanguage, "es-CR" | "en-US">> = {
  es: "es-CR",
  en: "en-US",
};

const DEFAULT_DATE_OPTIONS: Intl.DateTimeFormatOptions = {
  day: "2-digit",
  month: "2-digit",
  year: "numeric",
  hour: "2-digit",
  minute: "2-digit",
};

const ASSET_STATUS_KEYS: Readonly<Record<AssetLifecycleStatus, TranslationKey>> = {
  available: "statusAvailable",
  assigned: "statusAssigned",
  maintenance: "statusMaintenance",
  decommissioned: "statusDecommissioned",
};

export type AssetStatusPresentation =
  | { kind: "canonical"; label: string; rawValue?: never }
  | { kind: "unknown"; label: string; rawValue: string };

export function translate(
  language: AppLanguage,
  key: TranslationKey,
  parameters?: TranslationParameters,
): string {
  const template = translations[language][key];
  if (!parameters) return template;

  return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (placeholder, name: string) => {
    return Object.hasOwn(parameters, name) ? String(parameters[name]) : placeholder;
  });
}

export function getLocale(language: AppLanguage): "es-CR" | "en-US" {
  return LOCALE_BY_LANGUAGE[language];
}

export function formatDate(
  value: string | number | Date,
  language: AppLanguage,
  options: Intl.DateTimeFormatOptions = DEFAULT_DATE_OPTIONS,
): string {
  const date = value instanceof Date ? new Date(value.getTime()) : new Date(value);
  if (Number.isNaN(date.getTime())) return translate(language, "invalidDate");

  return new Intl.DateTimeFormat(getLocale(language), options).format(date);
}

function parseLocalDate(value: string | number | Date): Date | null {
  if (value instanceof Date) {
    const copy = new Date(value.getTime());
    return Number.isNaN(copy.getTime()) ? null : copy;
  }

  if (typeof value === "string") {
    const dateOnly = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
    if (dateOnly) {
      const localDate = new Date(Number(dateOnly[1]), Number(dateOnly[2]) - 1, Number(dateOnly[3]));
      return Number.isNaN(localDate.getTime()) ? null : localDate;
    }
  }

  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? null : date;
}

export function formatDateTime(
  value: string | number | Date,
  language: AppLanguage,
  dateFormat: DateFormatPreference = "dmy",
  timeFormat: TimeFormatPreference = "12h",
): string {
  const date = parseLocalDate(value);
  if (!date) return translate(language, "invalidDate");

  const year = String(date.getFullYear()).padStart(4, "0");
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  const dateLabel = dateFormat === "iso"
    ? `${year}-${month}-${day}`
    : `${day}/${month}/${year}`;
  const timeOptions: Intl.DateTimeFormatOptions = timeFormat === "24h"
    ? { hour: "2-digit", minute: "2-digit", hourCycle: "h23" }
    : { hour: "2-digit", minute: "2-digit", hour12: true };
  const timeLabel = new Intl.DateTimeFormat(getLocale(language), timeOptions).format(date);

  return `${dateLabel}, ${timeLabel}`;
}

export function formatNumber(
  value: number,
  language: AppLanguage,
  options?: Intl.NumberFormatOptions,
): string {
  return new Intl.NumberFormat(getLocale(language), options).format(value);
}

export function formatUsd(value: number): string {
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(value);
}

export function formatCurrency(
  value: number,
  currency: DisplayCurrencyPreference,
  language: AppLanguage,
): string {
  if (currency === "USD") return formatUsd(value);

  return new Intl.NumberFormat(getLocale(language), {
    style: "currency",
    currency,
    currencyDisplay: "narrowSymbol",
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(value);
}

export type CurrencyRates = Readonly<{
  crcPerUsd: number;
  eurPerUsd: number;
}>;

export function convertUsdAmount(
  amountUsd: number,
  currency: DisplayCurrencyPreference,
  rates: CurrencyRates,
): number {
  if (currency === "CRC") return amountUsd * rates.crcPerUsd;
  if (currency === "EUR") return amountUsd * rates.eurPerUsd;
  return amountUsd;
}

export function sumUsdCosts(costs: readonly (number | null | undefined)[]): number {
  return costs.reduce<number>((total, cost) => total + (cost ?? 0), 0);
}

export function sumAndConvertUsdCosts(
  costs: readonly (number | null | undefined)[],
  currency: DisplayCurrencyPreference,
  rates: CurrencyRates,
): number {
  return convertUsdAmount(sumUsdCosts(costs), currency, rates);
}

export function formatOptionalText(value: string | null | undefined, language: AppLanguage): string {
  return typeof value === "string" && value.trim().length > 0
    ? value
    : translate(language, "unspecified");
}

export function formatOptionalNotes(value: string | null | undefined, language: AppLanguage): string {
  return typeof value === "string" && value.trim().length > 0
    ? value
    : translate(language, "noObservations");
}

export function presentAssetStatus(
  value: string | null | undefined,
  language: AppLanguage,
): AssetStatusPresentation {
  if (typeof value !== "string" || value.trim().length === 0) {
    return { kind: "canonical", label: translate(language, "statusAvailable") };
  }

  if (Object.hasOwn(ASSET_STATUS_KEYS, value)) {
    const key = ASSET_STATUS_KEYS[value as AssetLifecycleStatus];
    return { kind: "canonical", label: translate(language, key) };
  }

  return { kind: "unknown", label: translate(language, "unknown"), rawValue: value };
}

export function formatGreeting(hour: number, language: AppLanguage): string {
  if (hour < 12) return translate(language, "greetingMorning");
  if (hour < 19) return translate(language, "greetingAfternoon");
  return translate(language, "greetingEvening");
}
